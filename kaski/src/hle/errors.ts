export type SceKernelError = (typeof SceKernelErrors)[keyof typeof SceKernelErrors];

/**
 * Check if value is an error code
 */
export function isError(value: number): boolean
{
  return (value & 0x80000000) !== 0;
}

/**
 * Get error name from code
 */
export function getErrorName(code: number): string
{
  for (const [name, value] of Object.entries(SceKernelErrors))
  {
    if (value === code) return name;
  }
  return `UNKNOWN_ERROR_${code.toString(16).toUpperCase()}`;
}
