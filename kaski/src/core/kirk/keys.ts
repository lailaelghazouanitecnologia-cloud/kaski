/**
 * Get key for KIRK CMD7 by keyseed
 */
export function getKirk7Key(keyseed: number): Uint8Array
{
  const key = KIRK7_KEYS[keyseed];
  if (!key)
  {
    throw new Error(`Unknown KIRK7 keyseed: 0x${keyseed.toString(16)}`);
  }
  return key;
}

